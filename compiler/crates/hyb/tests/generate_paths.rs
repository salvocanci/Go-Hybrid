//! `hyb generate`: the path-shape contract.
//!
//! Contract (row 13, design B): generate works against an existing go.mod
//! project from ANY path spelling — a bare filename, `./file.hy`, or a
//! directory walk. The bare-filename shape once broke: `Path::parent()`
//! of `calc.hy` is Some(""), and `read_dir("")` failed before a single
//! byte was read. This file pins the shapes so it stays fixed.

use std::fs;
use std::process::Command;

/// A minimal existing-Go-project fixture: one hand-written sibling .go
/// with a package clause + one .hy file, in a fresh temp dir (the std
/// `tempdir`-equivalent via env::temp_dir + a unique suffix).
struct SampleModule {
    root: std::path::PathBuf,
}

impl SampleModule {
    fn new(tag: &str) -> Self {
        let root = std::env::temp_dir().join(format!(
            "hyb-generate-{}-{}",
            tag,
            std::process::id()
        ));
        let _ = fs::remove_dir_all(&root);
        fs::create_dir_all(&root).expect("create temp module dir");
        fs::write(
            root.join("go.mod"),
            "module example.com/hybrid-demo\n\ngo 1.26\n",
        )
        .expect("write go.mod");
        fs::write(
            root.join("app.go"),
            "package demo\n\nimport \"fmt\"\n\nfunc main() { fmt.Println(\"app\") }\n",
        )
        .expect("write app.go");
        fs::write(
            root.join("calc.hy"),
            "fn add(a int, b int) int {\n    return a + b\n}\n",
        )
        .expect("write calc.hy");
        SampleModule { root }
    }

    fn hyb(&self, args: &[&str]) -> (i32, String, String) {
        let out = Command::new(env!("CARGO_BIN_EXE_hyb"))
            .args(args)
            .current_dir(&self.root)
            .output()
            .expect("spawn hyb");
        (
            out.status.code().unwrap_or(-1),
            String::from_utf8_lossy(&out.stdout).into_owned(),
            String::from_utf8_lossy(&out.stderr).into_owned(),
        )
    }
}

impl Drop for SampleModule {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.root);
    }
}

#[test]
fn bare_filename_and_dot_slash_and_dir_forms_all_fresh() {
    let m = SampleModule::new("shapes");

    // First pass WRITES: every spelling must succeed.
    // (One write is enough to produce the checked-in file for the checks.)
    let (code, stdout, stderr) = m.hyb(&["generate", "./calc.hy"]);
    assert_eq!(code, 0, "dot-slash write failed: {} {}", stdout, stderr);
    let written = fs::read_to_string(m.root.join("calc.hy.go")).expect("generated file");
    assert!(
        written.starts_with("// Code generated by hyb from "),
        "generated header contract"
    );

    // Bare filename (--check): the regression shape — parent() was Some("")
    // and the sibling walk died on read_dir("").
    let (code, stdout, stderr) = m.hyb(&["generate", "--check", "calc.hy"]);
    assert_eq!(code, 0, "bare filename --check failed: {} {}", stdout, stderr);
    assert!(stdout.contains("fresh"), "expected fresh: {}", stdout);

    // Dot-slash form still fresh.
    let (code, stdout, stderr) = m.hyb(&["generate", "--check", "./calc.hy"]);
    assert_eq!(code, 0, "dot-slash --check failed: {} {}", stdout, stderr);

    // Directory form still fresh.
    let (code, stdout, stderr) = m.hyb(&["generate", "--check", "."]);
    assert_eq!(code, 0, "directory --check failed: {} {}", stdout, stderr);
}

#[test]
fn bare_filename_generate_writes_too() {
    let m = SampleModule::new("bare-write");
    let (code, stdout, stderr) = m.hyb(&["generate", "calc.hy"]);
    assert_eq!(code, 0, "bare filename write failed: {} {}", stdout, stderr);
    assert!(
        m.root.join("calc.hy.go").exists(),
        "bare-filename generate must write beside the source"
    );
}
