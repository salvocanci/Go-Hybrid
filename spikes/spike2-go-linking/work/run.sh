#!/usr/bin/env bash
# Spike 2 driver: E1..E8. Prints PASS/FAIL per test with evidence; see ../RESULTS.md.
set -u
cd "$(dirname "$0")"
W="$(pwd)"
PASS=(); FAIL=()
ok()   { PASS+=("$1"); echo "PASS: $1 ${2:-}"; }
bad()  { FAIL+=("$1"); echo "FAIL: $1 ${2:-}"; }

echo "== E1: Go-source emission + //line round-trip =="
rm -rf emitted && mkdir -p emitted/hygen
python3 emit.py "$W/sample.hy" "$W/emitted/hygen/hello.hy.go" hygen
cat > emitted/go.mod <<'EOF'
module emitmod

go 1.26
EOF
cat > emitted/main.go <<'EOF'
package main

import (
	"fmt"
	"os"

	"emitmod/hygen"
)

func main() {
	if len(os.Args) > 1 && os.Args[1] == "boom" {
		hygen.Boom()
	}
	fmt.Println(hygen.Greet("spike2"))
	fmt.Println("asmDouble(21) =", hygen.AsmDouble(21))
}
EOF
# E2: emitted Go assembly alongside emitted Go source
cat > emitted/hygen/trampoline_amd64.s <<'EOF'
// Emitted Hybrid trampoline (spike-2 stand-in): proves go build links emitted .s.
#include "textflag.h"

TEXT ·asmDouble(SB), NOSPLIT, $0-16
	MOVQ	x+0(FP), AX
	ADDQ	AX, AX
	MOVQ	AX, ret+8(FP)
	RET
EOF
cat > emitted/hygen/decl.go <<'EOF'
package hygen

// AsmDouble is implemented in trampoline_amd64.s (emitted assembly).
func asmDouble(x uint64) uint64

// AsmDouble doubles x through the emitted trampoline.
func AsmDouble(x uint64) uint64 { return asmDouble(x) }
EOF
(cd emitted && go build -o app .) \
  && ok "E1a single go build (source+//line)" || bad "E1a build failed"
OUT="$(cd emitted && ./app)"
echo "$OUT" | grep -q "hello, spike2 (from Hybrid)" && ok "E1b runs correctly" || bad "E1b wrong output: $OUT"
echo "$OUT" | grep -q "asmDouble(21) = 42" && ok "E2 emitted .s builds+runs" || bad "E2 asm failed"

# E1c: runtime panic maps back to .hy
(cd emitted && ./app boom 2>&1 || true) | grep -q "sample.hy" \
  && ok "E1c panic stack maps to sample.hy" \
  || bad "E1c stack trace does not mention sample.hy"
# E1d: compile error maps back to .hy
mkdir -p errgen && python3 emit.py "$W/sample.hy" "$W/errgen/hello.hy.go" main
printf 'package main\nfunc main(){ }\n' > errgen/main.go 2>/dev/null || true
printf 'module errgen\n\ngo 1.26\n' > errgen/go.mod
# break the generated file at a mapped line (line 10 area => Greet body)
sed -i 's|return "hello, " + name + " (from Hybrid)"|return "hello, " + name + (((|' errgen/hello.hy.go
ERR="$(cd errgen && go build . 2>&1 || true)"
echo "$ERR" | grep -q "sample.hy" && ok "E1d compile errors map to sample.hy" || bad "E1d errors not mapped: $ERR"

echo "== E3: binary-only packages =="
mkdir -p bopkg && printf 'package bopkg\n' > bopkg/bopkg.go && printf 'module boptest\n\ngo 1.26\n' > bopkg/go.mod
printf '//go:binary-only-package\npackage bopkg\n' > bopkg/binonly.go
BERR="$(cd bopkg && go build ./... 2>&1 || true)"
echo "$BERR" | grep -qi "binary-only" && ok "E3 binary-only rejected (as registered)" || bad "E3 unexpected: $BERR"

echo "== E4: Rust staticlib via single go build (cgo LDFLAGS) =="
rm -rf rustlink && mkdir -p rustlink
LIBDIR="$W/../../spike1-call-overhead/work/rustrt/target/release"
ls "$LIBDIR/librustrt.a" >/dev/null 2>&1 || bad "E4 librustrt.a missing (run spike 1 first)"
cat > rustlink/go.mod <<'EOF'
module rustlink

go 1.26
EOF
cat > rustlink/main.go <<'EOF'
package main

/*
#cgo LDFLAGS: -L${SRCDIR}/../../../spike1-call-overhead/work/rustrt/target/release -l:librustrt.a -lpthread -ldl -lm
#include <stdint.h>
extern uint64_t hybrid_add(uint64_t a, uint64_t b);
*/
import "C"

import "fmt"

func main() {
	fmt.Println("rustlink: hybrid_add(40,2) =", uint64(C.hybrid_add(40, 2)))
}
EOF
(cd rustlink && go build -o app .) && R4="$(cd rustlink && ./app)" \
  && echo "$R4" | grep -q "42" && ok "E4 single go build links Rust staticlib" || bad "E4 failed: $R4"

echo "== E5: zero-install (no Rust toolchain on PATH; gcc present; CGO on) =="
rm -rf zeroinstall && mkdir -p zeroinstall/hybridpkg/lib zeroinstall/downer
cp "$LIBDIR/librustrt.a" zeroinstall/hybridpkg/lib/
cat > zeroinstall/hybridpkg/go.mod <<'EOF'
module hybridpkg

go 1.26
EOF
cat > zeroinstall/hybridpkg/hybrid.generated.go <<'EOF'
// Code generated by Hybrid. DO NOT EDIT.
package hybridpkg

/*
#cgo LDFLAGS: -L${SRCDIR}/lib -l:librustrt.a -lpthread -ldl -lm
#include <stdint.h>
extern uint64_t hybrid_add(uint64_t a, uint64_t b);
static uint64_t add_proxy(uint64_t a, uint64_t b) { return hybrid_add(a, b); }
*/
import "C"

// Add calls into the prebuilt Hybrid Rust artifact.
func Add(a, b uint64) uint64 { return uint64(C.add_proxy(C.uint64_t(a), C.uint64_t(b))) }
EOF
cat > zeroinstall/downer/go.mod <<'EOF'
module downer

go 1.26

require hybridpkg v0.0.0
replace hybridpkg => ../hybridpkg
EOF
cat > zeroinstall/downer/main.go <<'EOF'
package main

import (
	"fmt"

	"hybridpkg"
)

func main() { fmt.Println("downer: 40+2 =", hybridpkg.Add(40, 2)) }
EOF
# simulate "machine without Rust": strip cargo/rustc from PATH (keep go + gcc)
CLEANPATH="$(dirname "$(command -v go)"):/usr/bin:/bin"
ENVOUT="$(cd zeroinstall/downer && env PATH="$CLEANPATH" bash -lc 'command -v cargo; command -v rustc' 2>&1 || true)"
echo "PATH check (should be empty): [$ENVOUT]"
(cd zeroinstall/downer && env PATH="$CLEANPATH" CGO_ENABLED=1 go build -o app .) \
  && Z="$(cd zeroinstall/downer && env PATH="$CLEANPATH" ./app)" \
  && echo "$Z" | grep -q "40+2 = 42" \
  && ok "E5 zero-install build+run without Rust toolchain" || bad "E5 failed"

echo "== E6: CGO_ENABLED=0 (pure-Go vs Rust-calling packages) =="
G6="$(cd zeroinstall/downer && env PATH="$CLEANPATH" CGO_ENABLED=0 go build -o app . 2>&1 || true)"
echo "$G6" | grep -qiE "cgo|build constraints exclude" && ok "E6 Rust-calling pkg fails under CGO_ENABLED=0 (as registered)" || bad "E6 unexpected: $G6"
# pure-Go emitted package (no .s) DOES cross-build:
rm -rf puremod && mkdir -p puremod/hygen && python3 emit.py "$W/sample.hy" "$W/puremod/hygen/hello.hy.go" hygen
printf 'module puremod\n\ngo 1.26\n' > puremod/go.mod
(cd puremod && env CGO_ENABLED=0 GOARCH=arm64 go build ./... ) \
  && ok "E6b pure-Go emitted pkg cross-builds (CGO=0, arm64)" || bad "E6b pure cross failed"
# asm-bearing package on a foreign arch: expected to FAIL (per-arch asm gating is an emitter requirement)
X6="$(cd emitted && env CGO_ENABLED=0 GOARCH=arm64 go build ./... 2>&1 || true)"
echo "$X6" | grep -qiE "undefined|asmDouble|build|missing function body" && ok "E6c asm-bearing pkg fails on foreign arch (finding: gate per-arch asm)" || bad "E6c unexpected: $X6"

echo "== E7: cross-compile with cgo (arm64) =="
X7="$(cd zeroinstall/downer && env PATH="$CLEANPATH" CGO_ENABLED=1 GOARCH=arm64 go build -o app-arm . 2>&1 || true)"
echo "$X7" | grep -qi "arm64\|clang\|gcc\|toolchain\|cgo" && ok "E7 cgo cross-compile blocked w/o cross toolchain (as registered)" || bad "E7 unexpected: $X7"

echo "== E8: gofmt + go vet on emitted code =="
F8="$(gofmt -l emitted/hygen 2>&1 || true)"
[ -z "$F8" ] && ok "E8a gofmt clean" || bad "E8a gofmt: $F8"
(cd emitted && go vet ./... >/dev/null 2>&1) && ok "E8b go vet clean" || bad "E8b go vet failed"

echo
echo "==== SUMMARY: ${#PASS[@]} passed, ${#FAIL[@]} failed ===="
for p in "${PASS[@]:-}"; do [ -n "$p" ] && echo "  PASS $p"; done
for f in "${FAIL[@]:-}"; do [ -n "$f" ] && echo "  FAIL $f"; done
[ ${#FAIL[@]} -eq 0 ]
